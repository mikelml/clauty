type Props = {
  id: string;
  size?: number;
  radius?: number;
};

export function IntegrationLogo({ id, size = 32, radius }: Props) {
  const resolvedId = ALIASES[id] ?? id;
  const spec = BRANDS[resolvedId];
  const r = radius ?? Math.round(size * 0.28);

  if (!spec) {
    return (
      <View style={[styles.fallback, { width: size, height: size, borderRadius: r }]}>
        <Text style={[styles.fallbackText, { fontSize: size * 0.4 }]}>?</Text>
      </View>
    );
  }

  if (spec.kind === 'monogram') {
    const fontSize = spec.text.length > 2 ? size * 0.28 : size * 0.4;
    return (
      <View
        style={[
          styles.box,
          { width: size, height: size, borderRadius: r, backgroundColor: spec.bg },
        ]}
      >
        <Text
          style={{
            color: spec.fg,
            fontSize,
            fontWeight: '800',
            letterSpacing: spec.text.length > 2 ? -0.5 : 0,
          }}
        >
          {spec.text}
        </Text>
      </View>
    );
  }

  const svgSize = size * 0.58;
  return (
    <View
      style={[
        styles.box,
        { width: size, height: size, borderRadius: r, backgroundColor: spec.bg },
      ]}
    >
      <Svg width={svgSize} height={svgSize} viewBox="0 0 24 24">
        <Path d={spec.path} fill={spec.fg} />
      </Svg>
    </View>
  );
}

